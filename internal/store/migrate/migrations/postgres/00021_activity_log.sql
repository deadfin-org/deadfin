-- +goose Up
-- The server activity log (upstream ActivityLogs, ActivityLog.cs). user_id is
-- NULL for an entry without a user. It has no foreign key: an entry outlives
-- its user, as upstream. item_id is the N-format item ID text. severity is the
-- LogLevel name. The version is 00021 because the v0.4 line holds 00019 and
-- 00020; migrate.Up allows the out-of-order apply when the lines merge.
CREATE TABLE activity_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    overview TEXT,
    short_overview TEXT,
    type TEXT NOT NULL,
    user_id UUID,
    item_id TEXT,
    date_created TIMESTAMPTZ NOT NULL,
    severity TEXT NOT NULL
);
CREATE INDEX ix_activity_log_date_created ON activity_log(date_created, id);

-- +goose Down
DROP INDEX ix_activity_log_date_created;
DROP TABLE activity_log;
